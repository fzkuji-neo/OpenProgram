"use client"

// shadcn/ui Sidebar, radix-luma style. The class recipes below are the
// official registry's (npx shadcn add sidebar with style "radix-luma")
// copied verbatim: header, footer, separator, content, group, group
// label, group action, menu, menu button, menu action, menu badge,
// menu sub and sub button. Two adaptations:
//
//   * The official file also ships layout plumbing — SidebarProvider
//     (open state in a cookie, Cmd+B), a `fixed` container with a gap
//     placeholder, a mobile Sheet, and a Tooltip per button. This app
//     already owns all of that (open state in localStorage and the
//     runtime store, the resizable rail hook, the narrow-viewport
//     overlay, hover tips on controls only), so `Sidebar` here is just
//     the official *floating* shell: a 7px gutter around a rounded
//     card. It takes `open` and sets the same data-state /
//     data-collapsible attributes the official group-data-* classes
//     read, so every recipe below behaves as published.
//   * The floating card is borderless — `shadow-raised` (the per-theme
//     composer shadow pair) instead of `shadow-sm ring-1`, the same
//     deviation the input box and the elevated Button already carry.
//
// Change sizes at the call site through the official `size` variants,
// not by editing the official classes.
import * as React from "react"
import { cva, type VariantProps } from "class-variance-authority"
import * as Slot from "@radix-ui/react-slot"

import { cn } from "@/lib/utils"
import { Separator } from "@/components/ui/separator"

function Sidebar({
  side = "left",
  open = true,
  className,
  children,
  ...props
}: React.ComponentProps<"div"> & {
  side?: "left" | "right"
  open?: boolean
}) {
  return (
    <div
      className={cn("group peer flex h-full p-2 text-sidebar-foreground", className)}
      data-state={open ? "expanded" : "collapsed"}
      data-collapsible={open ? "" : "icon"}
      data-variant="floating"
      data-side={side}
      data-slot="sidebar"
      {...props}
    >
      <div
        data-sidebar="sidebar"
        data-slot="sidebar-inner"
        className="flex size-full flex-col bg-sidebar group-data-[variant=floating]:rounded-2xl group-data-[variant=floating]:shadow-raised"
      >
        {children}
      </div>
    </div>
  )
}

